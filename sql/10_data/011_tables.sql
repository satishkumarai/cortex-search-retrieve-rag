-- 011_tables.sql
-- Production schema for Knowledge Base, Customers, and Incoming Support Tickets

USE ROLE SEARCH_ADMIN_ROLE;
USE WAREHOUSE SEARCH_APP_WH;
USE DATABASE RETRIEVE_DEMO_DB;
USE SCHEMA KNOWLEDGE_CORPUS;

-- 1. Knowledge Base Articles (Corpus for Cortex Search)
CREATE OR REPLACE TABLE KNOWLEDGE_BASE_ARTICLES (
    ARTICLE_ID VARCHAR(64) PRIMARY KEY,
    ARTICLE_TITLE VARCHAR(256) NOT NULL,
    CATEGORY VARCHAR(64) NOT NULL,
    BODY_TEXT VARCHAR NOT NULL,
    LAST_UPDATED TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    AUTHOR VARCHAR(128)
);

-- 2. Customer Dimension
CREATE OR REPLACE TABLE CUSTOMERS (
    CUSTOMER_ID VARCHAR(64) PRIMARY KEY,
    CUSTOMER_NAME VARCHAR(256) NOT NULL,
    TIER VARCHAR(32) NOT NULL, -- 'ENTERPRISE', 'GROWTH', 'STANDARD'
    REGION VARCHAR(64) NOT NULL
);

-- 3. Live Support Tickets (Incoming stream for batch/real-time triage)
CREATE OR REPLACE TABLE OPEN_TICKETS (
    TICKET_ID VARCHAR(64) PRIMARY KEY,
    CUSTOMER_ID VARCHAR(64) REFERENCES CUSTOMERS(CUSTOMER_ID),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    ISSUE_DESCRIPTION VARCHAR NOT NULL,
    STATUS VARCHAR(32) DEFAULT 'OPEN',
    QUERY_OPTIONS VARIANT -- Custom per-row retrieval scoring config
);

-- Consumer grants
GRANT SELECT ON ALL TABLES IN SCHEMA RETRIEVE_DEMO_DB.KNOWLEDGE_CORPUS TO ROLE SEARCH_APP_USER_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RETRIEVE_DEMO_DB.KNOWLEDGE_CORPUS TO ROLE SEARCH_APP_USER_ROLE;
