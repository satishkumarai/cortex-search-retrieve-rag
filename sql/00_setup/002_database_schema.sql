-- 002_database_schema.sql
-- Database and schema creation with explicit access control

USE ROLE SYSADMIN;

CREATE DATABASE IF NOT EXISTS RETRIEVE_DEMO_DB
    COMMENT = 'Database housing production CORTEX_SEARCH_RETRIEVE demo assets';

CREATE SCHEMA IF NOT EXISTS RETRIEVE_DEMO_DB.KNOWLEDGE_CORPUS
    COMMENT = 'Source tables, staging, and Cortex Search Service objects';

-- Grant access to SEARCH_ADMIN_ROLE
GRANT ALL PRIVILEGES ON DATABASE RETRIEVE_DEMO_DB TO ROLE SEARCH_ADMIN_ROLE;
GRANT ALL PRIVILEGES ON ALL SCHEMAS IN DATABASE RETRIEVE_DEMO_DB TO ROLE SEARCH_ADMIN_ROLE;
GRANT ALL PRIVILEGES ON FUTURE SCHEMAS IN DATABASE RETRIEVE_DEMO_DB TO ROLE SEARCH_ADMIN_ROLE;

-- Grant USAGE to consumer application role
GRANT USAGE ON DATABASE RETRIEVE_DEMO_DB TO ROLE SEARCH_APP_USER_ROLE;
GRANT USAGE ON SCHEMA RETRIEVE_DEMO_DB.KNOWLEDGE_CORPUS TO ROLE SEARCH_APP_USER_ROLE;
