-- 051_monitoring.sql
-- Production Telemetry: Refresh history & Error Rate Inspection

USE ROLE SEARCH_ADMIN_ROLE;
USE WAREHOUSE SEARCH_APP_WH;
USE DATABASE RETRIEVE_DEMO_DB;
USE SCHEMA KNOWLEDGE_CORPUS;

-- 1. Inspect recent refresh history for Cortex Search Service
SELECT
    NAME,
    DATA_TIMESTAMP,
    STATE,
    ERROR,
    REFRESH_TRIGGER
FROM TABLE(INFORMATION_SCHEMA.CORTEX_SEARCH_REFRESH_HISTORY(
    NAME => 'RETRIEVE_DEMO_DB.KNOWLEDGE_CORPUS.KNOWLEDGE_BASE_SEARCH_SERVICE'
))
ORDER BY DATA_TIMESTAMP DESC;

-- 2. Inspect Indexed Contents and Embedding columns
SELECT
    ARTICLE_ID,
    ARTICLE_TITLE,
    CATEGORY
FROM TABLE(CORTEX_SEARCH_DATA_SCAN(
    SERVICE_NAME => 'RETRIEVE_DEMO_DB.KNOWLEDGE_CORPUS.KNOWLEDGE_BASE_SEARCH_SERVICE'
))
LIMIT 10;
